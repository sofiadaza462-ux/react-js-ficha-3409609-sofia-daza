function sumar(a, b) {
  const total = a + b;
  return total;
}
const resultadoSuma = sumar(10, 5);
console.log("suma", resultadoSuma);

function restar(a, b) {
  const total = a - b;
  return total;
}
const resultadoResta = restar(10, 5);
console.log("resta", resultadoResta);

function multiplicar(a, b) {
  const total = a * b;
  return total;
}
const resultadoMultiplicacion = multiplicar(10, 5);
console.log("multiplicación", resultadoMultiplicacion);

function dividir(a, b) {
  const total = a / b;
  return total;
}
const resultadoDivision = dividir(10, 2);
console.log("división", resultadoDivision);

function calcularPromedio(nota1, nota2, nota3) {
  const total = (nota1 + nota2 + nota3) / 3;
  return total;
}
const resultadoPromedio = calcularPromedio(4, 3, 4);
console.log("promedio", resultadoPromedio);